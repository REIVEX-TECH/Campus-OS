/**
 * Terms distinctive enough that containing one is itself the problem.
 *
 * Matched anywhere in a handle, because `SuperAdmin99` borrows exactly the
 * authority that plain `admin` would. The cost is the occasional innocent word
 * caught by a substring, which is the right side to err on for a name other
 * people are asked to trust.
 */
export const RESERVED_SUBSTRINGS: readonly string[] = [
  'admin',
  'administrator',
  'campusos',
  'faculty',
  'moderator',
  'official',
  'registrar',
  'staff',
  'sysadmin',
  'university',
];

